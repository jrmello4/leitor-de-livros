const catalogues = new Map<Locale, MessageCatalog>([['en', ENGLISH_CATALOG]]);
let activeLocale: Locale = 'en';

export function registerLocale(locale: Locale, catalogue: MessageCatalog): void {
  catalogues.set(locale, { ...catalogue });
}

export function setLocale(locale: Locale): void {
  activeLocale = catalogues.has(locale) ? locale : 'en';
}

export function getLocale(): Locale {
  return activeLocale;
}

export function hasTranslation(key: string, locale = activeLocale): boolean {
  return Boolean(catalogues.get(locale)?.[key] ?? ENGLISH_CATALOG[key]);
}

export function t(key: string, params: MessageParams = {}): string {
  const entry = catalogues.get(activeLocale)?.[key] ?? ENGLISH_CATALOG[key];
  if (entry === undefined) {
    return `[missing translation: ${key}]`;
  }
  const message = typeof entry === 'function' ? entry(params) : entry;
  return message.replace(/\{\{(\w+)\}\}/g, (_match, name: string) => String(params[name] ?? ''));
}

export function actionLabel(action: string): string {
  return t(`input.${action}`);
}

export function availableLocales(): { code: Locale; label: string }[] {
  return [
    { code: 'en', label: 'English' },
    { code: 'pt-BR', label: 'Português (Brasil)' },
  ];
}
